    internal static List<AssessmentForm> BuildForms()
        => Enumerable.Range(0, 5)
            .Select(BuildForm)
            .ToList();

    private static AssessmentForm BuildForm(int formIndex)
    {
        var definitions = FormBasics[formIndex]
            .Concat(TakeCyclic(EasyPool, 5, formIndex * 2))
            .Concat(TakeCyclic(MediumPool, 10, formIndex * 3))
            .Concat(TakeCyclic(HardPool, 5, formIndex))
            .ToList();

        return new AssessmentForm
        {
            InternalCode = $"FIQH-{(char)('A' + formIndex)}",
            IsActive = true,
            Questions = definitions.Select((definition, index) =>
                BuildQuestion(definition, index + 1, formIndex)).ToList()
        };
    }

    private static AssessmentQuestion BuildQuestion(
        QuestionDefinition definition,
        int displayOrder,
        int formIndex)
    {
        var choices = new[]
        {
            definition.CorrectChoice,
            definition.WrongChoiceOne,
            definition.WrongChoiceTwo,
            definition.WrongChoiceThree
        };
        var shift = (displayOrder + formIndex) % choices.Length;
        var rotatedChoices = choices.Skip(shift).Concat(choices.Take(shift));

        return new AssessmentQuestion
        {
            Text = definition.Text,
            DisplayOrder = displayOrder,
            Difficulty = displayOrder <= 10
                ? AssessmentQuestionDifficulty.Easy
                : displayOrder <= 20
                    ? AssessmentQuestionDifficulty.Medium
                    : AssessmentQuestionDifficulty.Hard,
            Choices = rotatedChoices.Select(choice => new AssessmentChoice
            {
                Text = choice,
                IsCorrect = choice == definition.CorrectChoice
            }).ToList()
        };
    }

    private static IEnumerable<QuestionDefinition> TakeCyclic(
        IReadOnlyList<QuestionDefinition> source,
        int count,
        int offset)
    {
        for (var index = 0; index < count; index++)
            yield return source[(offset + index) % source.Count];
    }

    private static QuestionDefinition Q(
        string text,
        string correctChoice,
        string wrongChoiceOne,
        string wrongChoiceTwo,
        string wrongChoiceThree)
        => new(text, correctChoice, wrongChoiceOne, wrongChoiceTwo, wrongChoiceThree);
